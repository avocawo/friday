"""A generated view; user notes live in a separate, untouched file."""
import os
import stat
import tempfile
from pathlib import Path

from . import profile, state
from .errors import FridayError
from .locks import locked


def render(card):
    lines = ["<!-- friday:generated " + card["key"] + " -->", "# " + card["key"], "", "| Поле | Значение |", "|---|---|",
             "| Статус | %s |" % card["status"], "| Обновлено | %s |" % card["updated_at"], "",
             "| Этап | Состояние | Доказательство |", "|---|---|---|"]
    for name, stage in sorted(card["stages"].items()):
        cells = [name, stage.get("status", "open"), stage.get("evidence", "")]
        lines.append("| " + " | ".join(str(cell).replace("|", "\\|").replace("\n", " ") for cell in cells) + " |")
    lines.extend(["", "| Решение | Значение |", "|---|---|"])
    for name, decision in sorted(card.get("decisions", {}).items()):
        cells = [name, decision.get("value", "")]
        lines.append("| " + " | ".join(str(cell).replace("|", "\\|").replace("\n", " ") for cell in cells) + " |")
    if card.get("planning_assumptions"):
        lines.extend(["", "## Допущения планирования", ""])
        lines.extend("- " + assumption.replace("\n", " ") for assumption in card["planning_assumptions"])
    lines.extend(["", "| Критерий | Этап | Доказательство |", "|---|---|---|"])
    for name, stage in sorted(card["stages"].items()):
        for criterion in stage.get("criteria", []):
            cells = [criterion, name, stage.get("evidence", "")]
            lines.append("| " + " | ".join(str(cell).replace("|", "\\|").replace("\n", " ") for cell in cells) + " |")
    return "\n".join(lines) + "\n"


def destination(profile, key):
    if not profile.get("journal_dir"):
        return None
    return Path(profile["journal_dir"]) / (state.validate_key(key) + ".md")


def sync(root, key):
    with locked(root, "task:" + state.validate_key(key)):
        card = state.read(root, key)
        path = destination(profile.load(card["profile"]), key)
        if path is None:
            return None
        path.parent.mkdir(parents=True, exist_ok=True)
        marker = ("<!-- friday:generated " + key + " -->\n").encode("utf-8")
        content = render(card).encode("utf-8")
        try:
            fd = os.open(str(path), os.O_RDWR | getattr(os, "O_NOFOLLOW", 0))
        except FileNotFoundError:
            fd = None
        except OSError as exc:
            raise FridayError("journal_conflict", "Cannot safely open journal: " + str(exc))
        if fd is not None:
            with os.fdopen(fd, "r+b") as handle:
                original = os.fstat(handle.fileno())
                if not stat.S_ISREG(original.st_mode) or original.st_nlink != 1 or handle.readline() != marker:
                    raise FridayError("journal_conflict", "Refusing to overwrite a file not generated by Friday: " + str(path))
                handle.seek(0)
                handle.write(content)
                handle.truncate()
                handle.flush()
                os.fsync(handle.fileno())
                try:
                    current = os.stat(str(path), follow_symlinks=False)
                except FileNotFoundError:
                    raise FridayError("journal_conflict", "Journal was moved during generation: " + str(path))
                if (original.st_dev, original.st_ino) != (current.st_dev, current.st_ino):
                    raise FridayError("journal_conflict", "Journal was replaced during generation: " + str(path))
            return str(path)
        name = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=str(path.parent), delete=False) as handle:
                name = handle.name
                handle.write(render(card))
                handle.flush()
                os.fsync(handle.fileno())
            try:
                os.link(name, path)
            except FileExistsError:
                raise FridayError("journal_conflict", "Journal appeared during generation: " + str(path))
            os.unlink(name)
            name = None
        finally:
            if name is not None:
                os.unlink(name)
        return str(path)
